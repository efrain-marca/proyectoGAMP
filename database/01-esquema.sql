SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS usuarios (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL,
 correo VARCHAR(190) NOT NULL UNIQUE, clave VARCHAR(200) NOT NULL,
 rol ENUM('admin','tecnico','finanzas','supervisor') NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (CHAR_LENGTH(nombre) BETWEEN 3 AND 120)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sesiones (
 token CHAR(64) CHARACTER SET ascii PRIMARY KEY, usuario INT UNSIGNED NOT NULL,
 vence DATETIME NOT NULL, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario) REFERENCES usuarios(id), INDEX (vence)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS intentos (
 clave CHAR(64) CHARACTER SET ascii PRIMARY KEY, cantidad SMALLINT UNSIGNED NOT NULL,
 vence DATETIME NOT NULL, INDEX (vence)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS proyectos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(160) NOT NULL, ubicacion VARCHAR(150) NOT NULL, unidad VARCHAR(120) NOT NULL,
 descripcion VARCHAR(1600) NOT NULL, inicio DATE NOT NULL, fin DATE NOT NULL,
 estado ENUM('planificado','ejecucion','suspendido','concluido') NOT NULL DEFAULT 'planificado',
 revision INT UNSIGNED NOT NULL DEFAULT 1, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 autor INT UNSIGNED NOT NULL, FOREIGN KEY(autor) REFERENCES usuarios(id), CHECK(fin>=inicio)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS responsables (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL, usuario INT UNSIGNED NOT NULL,
 funcion ENUM('tecnico','finanzas','supervisor') NOT NULL, inicio DATE NOT NULL, fin DATE NOT NULL,
 fin_original DATE NOT NULL, motivo VARCHAR(500) NOT NULL, autor INT UNSIGNED NOT NULL,
 registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(usuario) REFERENCES usuarios(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 INDEX (usuario,inicio,fin), INDEX (proyecto,funcion,inicio,fin), CHECK(fin>=inicio)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS documentos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL, nombre VARCHAR(180) NOT NULL,
 descripcion VARCHAR(500) NOT NULL, tipo VARCHAR(32) NOT NULL, bytes INT UNSIGNED NOT NULL, sha CHAR(64) NOT NULL,
 anterior INT UNSIGNED UNIQUE, vigente BOOLEAN NOT NULL DEFAULT TRUE,
 motivo VARCHAR(500) NOT NULL, autor INT UNSIGNED NOT NULL, fecha DATE NOT NULL,
 registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(anterior) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 UNIQUE(proyecto,sha), CHECK(bytes BETWEEN 1 AND 10485760)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS archivo_partes (
 documento INT UNSIGNED NOT NULL, numero SMALLINT UNSIGNED NOT NULL, datos MEDIUMBLOB NOT NULL,
 PRIMARY KEY(documento,numero), FOREIGN KEY(documento) REFERENCES documentos(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cambios_estado (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL,
 anterior VARCHAR(20), nuevo VARCHAR(20) NOT NULL, motivo VARCHAR(500) NOT NULL,
 documento INT UNSIGNED, autor INT UNSIGNED NOT NULL, fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS actividades (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL, nombre VARCHAR(150) NOT NULL,
 responsable INT UNSIGNED NOT NULL, inicio DATE NOT NULL, fin DATE NOT NULL,
 inicio_original DATE NOT NULL, fin_original DATE NOT NULL, autor INT UNSIGNED NOT NULL,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(responsable) REFERENCES usuarios(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 UNIQUE(proyecto,nombre), CHECK(fin>=inicio)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reprogramaciones (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actividad INT UNSIGNED NOT NULL,
 inicio_previo DATE NOT NULL, fin_previo DATE NOT NULL, inicio DATE NOT NULL, fin DATE NOT NULL,
 motivo VARCHAR(500) NOT NULL, documento INT UNSIGNED NOT NULL, autor INT UNSIGNED NOT NULL,
 fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actividad) REFERENCES actividades(id), FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 CHECK(fin>=inicio)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS presupuesto (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL, monto DECIMAL(15,2) NOT NULL,
 previo DECIMAL(15,2), moneda CHAR(3) NOT NULL DEFAULT 'BOB', vigente BOOLEAN NOT NULL DEFAULT TRUE,
 fecha DATE NOT NULL, motivo VARCHAR(500) NOT NULL, documento INT UNSIGNED NOT NULL, autor INT UNSIGNED NOT NULL,
 registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 unico_vigente INT UNSIGNED GENERATED ALWAYS AS (IF(vigente=1,proyecto,NULL)) STORED UNIQUE,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 INDEX(proyecto,fecha), CHECK(monto>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS avances_fisicos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actividad INT UNSIGNED NOT NULL, corte DATE NOT NULL,
 porcentaje DECIMAL(5,2) NOT NULL, observacion VARCHAR(750) NOT NULL, documento INT UNSIGNED,
 reemplaza INT UNSIGNED UNIQUE, vigente BOOLEAN NOT NULL DEFAULT TRUE,
 motivo VARCHAR(500) NOT NULL, autor INT UNSIGNED NOT NULL, registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 corte_vigente DATE GENERATED ALWAYS AS (IF(vigente=1,corte,NULL)) STORED, UNIQUE(actividad,corte_vigente),
 FOREIGN KEY(actividad) REFERENCES actividades(id), FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(reemplaza) REFERENCES avances_fisicos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 INDEX(actividad,corte), CHECK(porcentaje BETWEEN 0 AND 100)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS avances_financieros (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL,
 periodo CHAR(7) NOT NULL, corte DATE NOT NULL, acumulado DECIMAL(15,2) NOT NULL, presupuesto INT UNSIGNED NOT NULL,
 exceso BOOLEAN NOT NULL, observacion VARCHAR(750) NOT NULL, documento INT UNSIGNED NOT NULL,
 reemplaza INT UNSIGNED UNIQUE, vigente BOOLEAN NOT NULL DEFAULT TRUE,
 motivo VARCHAR(500) NOT NULL, autor INT UNSIGNED NOT NULL, registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 periodo_vigente INT GENERATED ALWAYS AS (IF(vigente=1,YEAR(corte)*100+MONTH(corte),NULL)) STORED, UNIQUE(proyecto,periodo_vigente),
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(presupuesto) REFERENCES presupuesto(id), FOREIGN KEY(reemplaza) REFERENCES avances_financieros(id),
 FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 INDEX(proyecto,corte), CHECK(acumulado>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS incidencias (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL,
 descripcion VARCHAR(750) NOT NULL, fecha DATE NOT NULL, responsable INT UNSIGNED NOT NULL,
 estado ENUM('pendiente','atencion','resuelta') NOT NULL DEFAULT 'pendiente',
 autor INT UNSIGNED NOT NULL, registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(responsable) REFERENCES usuarios(id), FOREIGN KEY(autor) REFERENCES usuarios(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS acciones_incidencia (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, incidencia INT UNSIGNED NOT NULL, descripcion VARCHAR(750) NOT NULL,
 fecha DATE NOT NULL, documento INT UNSIGNED, cierre BOOLEAN NOT NULL, autor INT UNSIGNED NOT NULL,
 registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(incidencia) REFERENCES incidencias(id), FOREIGN KEY(documento) REFERENCES documentos(id), FOREIGN KEY(autor) REFERENCES usuarios(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS alertas (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actividad INT UNSIGNED NOT NULL,
 tipo ENUM('vencida','proxima') NOT NULL, fin DATE NOT NULL,
 estado ENUM('abierta','atendida','cerrada') NOT NULL DEFAULT 'abierta',
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, atendido DATETIME, autor INT UNSIGNED, observacion VARCHAR(500),
 FOREIGN KEY(actividad) REFERENCES actividades(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 UNIQUE(actividad,tipo,fin)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS versiones_publicas (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL,
 ficha JSON NOT NULL, activa BOOLEAN NOT NULL DEFAULT TRUE, aprobada DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 autor INT UNSIGNED NOT NULL, retirada DATETIME, retiro_autor INT UNSIGNED, motivo VARCHAR(500),
 unica_activa INT UNSIGNED GENERATED ALWAYS AS (IF(activa=1,proyecto,NULL)) STORED UNIQUE,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(autor) REFERENCES usuarios(id), FOREIGN KEY(retiro_autor) REFERENCES usuarios(id),
 INDEX(proyecto,activa)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS archivos_publicos (
 version INT UNSIGNED NOT NULL, documento INT UNSIGNED NOT NULL, PRIMARY KEY(version,documento),
 FOREIGN KEY(version) REFERENCES versiones_publicas(id), FOREIGN KEY(documento) REFERENCES documentos(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS historial (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED, entidad VARCHAR(40) NOT NULL,
 registro INT UNSIGNED NOT NULL, accion VARCHAR(40) NOT NULL, anterior JSON, nuevo JSON,
 motivo VARCHAR(500) NOT NULL, autor INT UNSIGNED NOT NULL, fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(autor) REFERENCES usuarios(id),
 INDEX(proyecto,fecha,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS operaciones (
 usuario INT UNSIGNED NOT NULL, llave CHAR(36) CHARACTER SET ascii NOT NULL,
 fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(usuario,llave), FOREIGN KEY(usuario) REFERENCES usuarios(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS inspecciones_obra (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, proyecto INT UNSIGNED NOT NULL, fecha DATE NOT NULL,
 observacion VARCHAR(750) NOT NULL, documento INT UNSIGNED NOT NULL, autor INT UNSIGNED NOT NULL,
 registrado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(proyecto) REFERENCES proyectos(id), FOREIGN KEY(documento) REFERENCES documentos(id),
 FOREIGN KEY(autor) REFERENCES usuarios(id), UNIQUE(proyecto,fecha,documento,autor),
 CHECK(CHAR_LENGTH(TRIM(observacion)) BETWEEN 5 AND 750)
) ENGINE=InnoDB;
